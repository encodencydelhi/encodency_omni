type LeadSeed = Omit<
  Lead,
  "timeline" | "notes" | "tasks" | "appointments" | "documents" | "consent"
> &
  Partial<
    Pick<
      Lead,
      "timeline" | "notes" | "tasks" | "appointments" | "documents" | "consent"
    >
  >;

function lead(seed: LeadSeed): Lead {
  const formName =
    instantForms.find((f) => f.id === seed.formId)?.name ?? "an instant form";
  return {
    consent: "Consented to be contacted by phone and WhatsApp at submission.",
    timeline: [
      {
        at: seed.submittedAt,
        actor: "Meta",
        type: "lead",
        text: `Lead submitted through ${formName}.`,
      },
    ],
    notes: [],
    tasks: [],
    appointments: [],
    documents: [],
    ...seed,
  };
}

