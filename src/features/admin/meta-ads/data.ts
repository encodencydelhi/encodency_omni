export const getCampaign = (id: string) => campaigns.find((c) => c.id === id);
export const getAdSet = (id: string) => adSets.find((a) => a.id === id);
export const getAd = (id: string) => ads.find((a) => a.id === id);
export const getForm = (id: string) => instantForms.find((f) => f.id === id);
export const getLead = (id: string) => leads.find((l) => l.id === id);
export const getCreative = (id: string) => creatives.find((c) => c.id === id);

export const adSetsOfCampaign = (campaignId: string) =>
  adSets.filter((a) => a.campaignId === campaignId);
export const adsOfCampaign = (campaignId: string) =>
  ads.filter((a) => a.campaignId === campaignId);
export const adsOfAdSet = (adSetId: string) =>
  ads.filter((a) => a.adSetId === adSetId);
export const adsOfForm = (formId: string) =>
  ads.filter((a) => a.formId === formId);

export const campaignsOfForm = (formId: string): Campaign[] =>
  Array.from(new Set(adsOfForm(formId).map((a) => a.campaignId)))
    .map(getCampaign)
    .filter((c): c is Campaign => Boolean(c));

export const leadsOf = (
  filter: Partial<Pick<Lead, "campaignId" | "adSetId" | "adId" | "formId">>,
) =>
  leads.filter((l) =>
    Object.entries(filter).every(
      ([key, value]) => !value || l[key as keyof Lead] === value,
    ),
  );

